[CmdletBinding()]
param(
    [switch]$Check
)

$ErrorActionPreference = "Stop"
$repoRoot = Resolve-Path (Join-Path $PSScriptRoot "../..")
$outputRelative = "artifacts/generated/ownership-manifest.md"
$outputPath = Join-Path $repoRoot $outputRelative

function Get-RepoRelativePath([string]$FullName) {
    $root = $repoRoot.ProviderPath.TrimEnd("\", "/")
    $full = (Resolve-Path $FullName).ProviderPath
    if ($full.StartsWith($root, [System.StringComparison]::OrdinalIgnoreCase)) {
        return $full.Substring($root.Length).TrimStart("\", "/").Replace("\", "/")
    }
    return $full.Replace("\", "/")
}

$specFiles = Get-ChildItem (Join-Path $repoRoot "specs") -Recurse -File -Include "*.spec.md", "vision.md", "system-context.md", "security-overview.md" |
    Sort-Object FullName

$records = New-Object System.Collections.Generic.List[object]
foreach ($spec in $specFiles) {
    $relative = Get-RepoRelativePath $spec.FullName
    $content = Get-Content $spec.FullName -Raw
    if ($content -notmatch "(?s)^---\n(?<meta>.*?)\n---\n") { continue }
    $meta = $Matches.meta
    $id = ([regex]::Match($meta, "(?m)^id:\s*(?<value>[A-Za-z0-9_.-]+)\s*$")).Groups["value"].Value
    $ownsMatch = [regex]::Match($meta, "(?ms)^owns:\s*\n(?<items>(?:\s+-\s+.+\n?)+)")
    $owned = New-Object System.Collections.Generic.List[string]
    if ($ownsMatch.Success) {
        foreach ($line in ($ownsMatch.Groups["items"].Value -split "\n")) {
            if ($line -match "^\s+-\s+(?<path>.+?)\s*$") { $owned.Add($Matches.path.Trim().Replace("\", "/")) }
        }
    }
    $records.Add([pscustomobject]@{ Id = $id; Spec = $relative; Owns = $owned })
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("<!-- Generated by tools/sdd/generate-build-files.ps1. Do not edit by hand. -->")
$lines.Add("# Spec Ownership Manifest")
$lines.Add("")
$lines.Add("This file is derived from the ``owns`` metadata of specs under ``specs/``.")
$lines.Add("Regenerate with ``powershell -ExecutionPolicy Bypass -File ./tools/sdd/generate-build-files.ps1``.")
$lines.Add("")
$lines.Add("| Spec | Spec Id | Owned Path |")
$lines.Add("| --- | --- | --- |")
foreach ($record in ($records | Sort-Object Spec)) {
    if ($record.Owns.Count -eq 0) {
        $lines.Add("| $($record.Spec) | $($record.Id) | _none_ |")
        continue
    }
    foreach ($path in $record.Owns) {
        $lines.Add("| $($record.Spec) | $($record.Id) | ``$path`` |")
    }
}
$lines.Add("")

$expected = ($lines -join "`n")

if ($Check) {
    if (-not (Test-Path $outputPath)) {
        Write-Host "Generated build-file check failed: missing $outputRelative" -ForegroundColor Red
        Write-Host "Run: powershell -ExecutionPolicy Bypass -File ./tools/sdd/generate-build-files.ps1" -ForegroundColor Red
        exit 1
    }
    $actual = (Get-Content $outputPath -Raw) -replace "`r`n", "`n"
    if ($actual.TrimEnd("`n") -ne $expected.TrimEnd("`n")) {
        Write-Host "Generated build-file check failed: $outputRelative is out of date" -ForegroundColor Red
        Write-Host "Run: powershell -ExecutionPolicy Bypass -File ./tools/sdd/generate-build-files.ps1" -ForegroundColor Red
        exit 1
    }
    Write-Host "Generated build-file check passed." -ForegroundColor Green
    exit 0
}

New-Item -ItemType Directory -Force -Path (Split-Path $outputPath -Parent) | Out-Null
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($outputPath, $expected, $utf8)
Write-Host "Wrote $outputRelative" -ForegroundColor Green

